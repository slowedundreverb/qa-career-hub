import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { curriculum, tracks } from '../src/data/curriculum.js';
import { questions } from '../src/data/questions.js';

const hasRussian = (value) => /[А-Яа-яЁё]/.test(value);
const values = [];
const collect = (value) => {
  if (typeof value === 'string' && hasRussian(value)) values.push(value);
  else if (Array.isArray(value)) value.forEach(collect);
  else if (value && typeof value === 'object') Object.values(value).forEach(collect);
};

collect(curriculum);
collect(tracks);
collect(questions);

const unique = [...new Set(values)];
const translations = new Map();
const batches = [];
let batch = [];
let size = 0;

for (const value of unique) {
  if (batch.length >= 18 || size + value.length > 3600) {
    batches.push(batch);
    batch = [];
    size = 0;
  }
  batch.push(value);
  size += value.length;
}
if (batch.length) batches.push(batch);

async function translateBatch(items, batchIndex) {
  const source = items.map((value, index) => `<<<${index}>>>\n${value}`).join('\n');
  const url = new URL('https://translate.googleapis.com/translate_a/single');
  Object.entries({ client: 'gtx', sl: 'ru', tl: 'en', dt: 't', q: source }).forEach(([key, value]) => url.searchParams.set(key, value));
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Translation batch ${batchIndex + 1} failed: ${response.status}`);
  const payload = await response.json();
  const translated = payload[0].map((part) => part[0]).join('');
  const matches = [...translated.matchAll(/<<<(\d+)>>>\s*([\s\S]*?)(?=\n<<<\d+>>>|$)/g)];
  if (matches.length !== items.length) throw new Error(`Translation batch ${batchIndex + 1}: expected ${items.length}, received ${matches.length}`);
  for (const match of matches) translations.set(items[Number(match[1])], match[2].trim());
}

for (let offset = 0; offset < batches.length; offset += 4) {
  await Promise.all(batches.slice(offset, offset + 4).map((items, index) => translateBatch(items, offset + index)));
  process.stdout.write(`Translated ${Math.min(offset + 4, batches.length)} / ${batches.length} batches\r`);
}

const polish = (value) => value
  .replace(/\bSystemic\b/g, 'System')
  .replace(/\bLimit values\b/g, 'Boundary values')
  .replace(/\bcutoff values\b/g, 'boundary values')
  .replace(/application software interface/gi, 'application programming interface')
  .replace(/\bassembly\b/gi, (match) => match[0] === 'A' ? 'Build' : 'build')
  .replace(/^Productivity\.$/, 'Performance.');

const localize = (value) => {
  if (typeof value === 'string') return polish(translations.get(value) || value);
  if (Array.isArray(value)) return value.map(localize);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, localize(child)]));
  return value;
};

const output = `// Generated by scripts/generate-english-content.mjs.\n// Regenerate after changing the Russian learning source.\nexport const curriculumEn = ${JSON.stringify(localize(curriculum), null, 2)};\n\nexport const tracksEn = ${JSON.stringify(localize(tracks), null, 2)};\n\nexport const questionsEn = ${JSON.stringify(localize(questions), null, 2)};\n`;
await writeFile(resolve('src/data/english-content.js'), output);
console.log(`\nSaved ${translations.size} translations.`);
