import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isAgency, sectorOf } from '../src/sectors.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { ADZUNA_APP_ID: appId, ADZUNA_APP_KEY: appKey } = process.env;
if (!appId || !appKey) {
  console.log('Adzuna credentials are not set: market statistics left unchanged.');
  process.exit(0);
}

// Every market Adzuna covers. Cyprus is not among them; the app uses the site's own Cyprus vacancies.
const countries = ['GB', 'US', 'DE', 'FR', 'NL', 'PL', 'ES', 'IT', 'AT', 'BE', 'CH', 'CA', 'AU', 'NZ', 'IN', 'SG', 'ZA', 'BR', 'MX'];
// IT category only: without it "QA" titles are flooded by food and manufacturing quality control.
const queries = [
  { title: 'qa', counted: true },
  { title: 'tester', counted: true },
  // Banks and brokers are rare among the latest ads, so they get a sample of their own.
  { title: 'qa', anyOf: 'bank banking trading broker brokerage fintech payments' }
];
const perSector = 12;
const sleep = ms => new Promise(done => setTimeout(done, ms));
const previous = await import('../src/data/market.js').then(module => module.market).catch(() => ({ countries: {} }));

async function search(country, { title, anyOf }) {
  const url = `https://api.adzuna.com/v1/api/jobs/${country.toLowerCase()}/search/1?app_id=${appId}&app_key=${appKey}&results_per_page=50&category=it-jobs&title_only=${title}${anyOf ? `&what_or=${encodeURIComponent(anyOf)}` : ''}&content-type=application/json`;
  for (let attempt = 1; ; attempt++) {
    const response = await fetch(url);
    if (response.ok) return response.json();
    if (attempt === 3 || (response.status !== 429 && response.status < 500)) throw new Error(`HTTP ${response.status}`);
    await sleep(20_000);
  }
}

// Top employers of each sector, so a few bank vacancies are not crowded out by large IT vendors.
const rank = counts => {
  const kept = { bank: 0, trading: 0, other: 0 };
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([name, count]) => ({ name, count, sector: sectorOf(name) }))
    .filter(company => kept[company.sector]++ < perSector);
};

const result = {};
let failures = 0;
for (const country of countries) {
  try {
    let count = 0;
    const ads = new Map();
    for (const query of queries) {
      const data = await search(country, query);
      // shortcut: a title like "QA Tester" is counted under both words; fine for comparing countries, use a deduplicated total if exact numbers matter.
      if (query.counted) count += data.count || 0;
      for (const ad of data.results || []) ads.set(ad.id, ad.company?.display_name?.trim());
      await sleep(3_000); // Adzuna allows about 25 requests a minute.
    }
    // The same employer shows up as "Deutsche Bank" and "deutsche bank"; keep the first spelling.
    const spelling = new Map();
    const companies = new Map();
    for (const name of ads.values()) {
      if (!name || isAgency(name)) continue;
      const display = spelling.get(name.toLowerCase()) || spelling.set(name.toLowerCase(), name).get(name.toLowerCase());
      companies.set(display, (companies.get(display) || 0) + 1);
    }
    result[country] = { count, companies: rank(companies) };
    console.log(`✓ ${country}: ${count} QA roles, ${companies.size} employers in the sample`);
  } catch (error) {
    failures++;
    if (previous.countries[country]) result[country] = previous.countries[country];
    console.warn(`× ${country}: ${error.message}${previous.countries[country] ? ' · kept the previous numbers' : ''}`);
  }
}

if (failures === countries.length) throw new Error('Adzuna returned no data for any country');

const world = new Map();
for (const { companies } of Object.values(result)) {
  for (const { name, count } of companies) world.set(name, (world.get(name) || 0) + count);
}
const market = { generatedAt: new Date().toISOString(), source: 'Adzuna', countries: result, world: rank(world) };
await writeFile(resolve(root, 'src/data/market.js'), `// Generated by scripts/update-market.mjs from the Adzuna API.\nexport const market = ${JSON.stringify(market, null, 2)};\n`);
console.log(`Market statistics saved for ${Object.keys(result).length} countries.`);
