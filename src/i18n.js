const preserveWhitespace = (original, replacement) => {
  const start = original.match(/^\s*/)?.[0] || '';
  const end = original.match(/\s*$/)?.[0] || '';
  return `${start}${replacement}${end}`;
};

export function translateUiText(value, locale) {
  if (locale !== 'en' || !value) return value;
  const trimmed = value.trim();
  if (!trimmed) return value;
  let result = en[trimmed];
  if (!result) {
    const patterns = [
      [/^(\d+) тем$/, '$1 topics'],
      [/^(\d+) \/ (\d+) тем$/, '$1 / $2 topics'],
      [/^(\d+) ответов$/, '$1 answers'],
      [/^(\d+) вопросов$/, '$1 questions'],
      [/^(\d+) мин$/, '$1 min'],
      [/^(.*) · (\d+) минут$/, '$1 · $2 minutes'],
      [/^(\d+) вакансий после фильтрации$/, '$1 jobs after filtering'],
      [/^(\d+) из (\d+) компаний$/, '$1 of $2 companies'],
      [/^(\d+) компаний под наблюдением$/, '$1 companies tracked'],
      [/^Все компании · (\d+)$/, 'All companies · $1'],
      [/^(.*) · 0 QA-вакансий$/, '$1 · 0 QA jobs'],
      [/^(.*) · только career-ссылка$/, '$1 · career page only'],
      [/^(\d+) · ссылка$/, '$1 · career page'],
      [/^(\d+) получено через настроенный API$/, '$1 received through the configured API'],
      [/^(\d+)% совпадение$/, '$1% match'],
      [/^(\d+) коротких разборов для повторения перед интервью\.$/, '$1 concise explanations to review before an interview.'],
      [/^Последняя проверка: (.+)$/, 'Last checked: $1'],
      [/^проверено (.+)$/, 'checked $1'],
      [/^Правильный ответ: (.+)$/, 'Correct answer: $1'],
      [/^ВОПРОС (.+)$/, 'QUESTION $1'],
      [/^Есть (\d+) активных позиций, (\d+) — с фокусом на Кипр\.$/, '$1 active roles, including $2 focused on Cyprus.'],
      [/^Запустите обновление, чтобы наполнить агрегатор официальными вакансиями\.$/, 'Run an update to load official job postings.'],
      [/^История версий, текущая версия (.+)$/, 'Version history, current version $1'],
      [/^Сессия завершена\. Общая точность: (.+)$/, 'Session complete. Overall accuracy: $1']
    ];
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(trimmed)) {
        result = trimmed.replace(pattern, replacement);
        break;
      }
    }
  }
  return result ? preserveWhitespace(value, result) : value;
}

export function localizeDocument(root, locale) {
  document.documentElement.lang = locale;
  document.title = locale === 'en' ? 'QA Career Hub — jobs and interview preparation' : 'QA Career Hub — вакансии и подготовка';
  document.querySelector('meta[name="description"]')?.setAttribute('content', locale === 'en'
    ? 'QA Career Hub: international jobs and structured interview preparation for QA and AQA professionals.'
    : 'Персональный QA Career Hub: вакансии и подготовка к собеседованиям QA/AQA.');
  if (locale !== 'en') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => { node.nodeValue = translateUiText(node.nodeValue, locale); });
  root.querySelectorAll('[placeholder],[aria-label],[title]').forEach((element) => {
    ['placeholder', 'aria-label', 'title'].forEach((attribute) => {
      if (element.hasAttribute(attribute)) element.setAttribute(attribute, translateUiText(element.getAttribute(attribute), locale));
    });
  });
}
